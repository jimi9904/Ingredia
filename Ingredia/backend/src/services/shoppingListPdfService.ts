import PDFDocument from 'pdfkit';
import { IRecipe } from '../models/Recipe.js';

export interface ShoppingListData {
  recipe: IRecipe;
  missing: any[];
  pantry_has: any[];
}

export const createShoppingListPDF = (data: ShoppingListData): Promise<Buffer> => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 40 });
    const buffers: Buffer[] = [];

    doc.on('data', buffers.push.bind(buffers));
    doc.on('end', () => {
      const pdfBuffer = Buffer.concat(buffers);
      resolve(pdfBuffer);
    });
    doc.on('error', reject);

    // Title & Header
    doc.fillColor('#E85D24').fontSize(22).font('Helvetica-Bold').text(data.recipe.title);
    doc.moveDown(0.2);
    doc
      .fillColor('#666666')
      .fontSize(11)
      .font('Helvetica')
      .text(
        `Servings: ${data.recipe.servings || 1}  |  Generated: ${new Date().toLocaleDateString(
          'en-US',
          { month: 'short', day: 'numeric', year: 'numeric' }
        )}`
      );
    doc.moveDown(1.5);

    // Section 1: To Buy
    doc.fillColor('#1D9E75').fontSize(14).font('Helvetica-Bold').text('To Buy');
    doc.moveDown(0.5);

    if (data.missing.length === 0) {
      doc
        .fillColor('#555555')
        .fontSize(11)
        .font('Helvetica-Oblique')
        .text('You have all ingredients in your pantry!');
      doc.moveDown(1);
    } else {
      // Table Header
      const col1 = 40;
      const col2 = 320;
      let y = doc.y;

      doc.fillColor('#333333').fontSize(10).font('Helvetica-Bold');
      doc.text('Ingredient', col1, y);
      doc.text('Quantity & Unit', col2, y);
      doc.moveDown(0.5);
      doc.strokeColor('#E0E0E0').lineWidth(1).moveTo(col1, doc.y).lineTo(550, doc.y).stroke();
      doc.moveDown(0.5);

      // Rows
      doc.font('Helvetica').fontSize(10).fillColor('#333333');
      for (const ing of data.missing) {
        const name = typeof ing === 'object' && ing !== null ? ing.name || 'Ingredient' : String(ing);
        const qty =
          typeof ing === 'object' && ing !== null
            ? `${ing.quantity || ''} ${ing.unit || ''}`.trim()
            : '';

        y = doc.y;
        doc.text(`• ${name}`, col1, y);
        doc.text(qty || '-', col2, y);
        doc.moveDown(0.4);
      }
      doc.moveDown(1.2);
    }

    // Section 2: Already in Pantry
    if (data.pantry_has.length > 0) {
      doc.fillColor('#666666').fontSize(13).font('Helvetica-Bold').text('Already in Pantry');
      doc.moveDown(0.5);

      const col1 = 40;
      const col2 = 320;
      let y = doc.y;

      doc.fillColor('#777777').fontSize(10).font('Helvetica-Bold');
      doc.text('Ingredient', col1, y);
      doc.text('Quantity & Unit', col2, y);
      doc.moveDown(0.5);
      doc.strokeColor('#EAEAEA').lineWidth(1).moveTo(col1, doc.y).lineTo(550, doc.y).stroke();
      doc.moveDown(0.5);

      doc.font('Helvetica').fontSize(10).fillColor('#777777');
      for (const ing of data.pantry_has) {
        const name = typeof ing === 'object' && ing !== null ? ing.name || 'Ingredient' : String(ing);
        const qty =
          typeof ing === 'object' && ing !== null
            ? `${ing.quantity || ''} ${ing.unit || ''}`.trim()
            : '';

        y = doc.y;
        doc.text(`✓ ${name}`, col1, y);
        doc.text(qty || '-', col2, y);
        doc.moveDown(0.4);
      }
      doc.moveDown(1);
    }

    // Footer
    doc
      .fontSize(9)
      .fillColor('#AAAAAA')
      .text('Generated by Ingredia Recipe Platform', 40, 750, {
        align: 'center',
        width: 510,
      });

    doc.end();
  });
};

